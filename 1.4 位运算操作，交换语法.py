# << 左移: 每移动一位, 相当于 * 2
n = 10
n = n << 1 # 相当于 10 * 2 = 20
print(f'{n = }')

# >> 右移: 每移动一位, 相当于 // 2
m = 10
m = m >> 1 # 相当于 10 // 2 = 20
print(f'{m = }')

# & 按位与: 全 1 为 1
a = 10
b = 7
'''
10 0000 1010
7  0000 0111
-----------------
   0000 0010 结果为: 2
'''
c = a & b
print(f'{c = }')
# | 按位或 : 有 1 就 1
'''
10 0000 1010
7  0000 0111
-----------------
   0000 1111 结果为: 15
'''
d = a | b
print(f'{d = }')


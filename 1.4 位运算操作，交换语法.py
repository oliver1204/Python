# js有，前自增 ++1 以及后自增++。 但是python没有，只有一种自增方式
# x = x + y # x = 30
# y = x - y # y = 10
# x = x - y # x = 20

# 方式三 : Python 语言特有的交换语法, 其它语言没有该语法
# x, y = y, x

# 方式四 : Python的交换语法，在底层是位运算 - 异或操作 
# (异或操作的口诀: 相同为0, 不同为1)
